// Builds a separate Devnet test copy of the website (never the production site): every page carries a fixed
// "Devnet test" banner, the quote token is shown as TEST-USDC (a worthless Devnet test token, never real USDC),
// search engines are told not to index it and site-config.js points at Devnet with the given program.
// The production files in heli/website are only read.
//   node scripts/devnet_preview.mjs <outdir> [--program <ID>] [--sha256 <ELF hash> --length <bytes>]
// Publish it as a Cloudflare Pages *preview* branch (e.g. --branch devnet), never as the production branch.
import { readFileSync, writeFileSync, mkdirSync, cpSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2), out = args[0], flag = n => { const i = args.indexOf(n); return i > 0 ? args[i + 1] : undefined; };
if (!out || out.startsWith('--')) throw Error('usage: node scripts/devnet_preview.mjs <outdir> [--program <ID>] [--sha256 <hex> --length <bytes>]');
const site = fileURLToPath(new URL('../../website/', import.meta.url));
if (existsSync(out) && readdirSync(out).length && !existsSync(join(out, 'devnet-banner.js'))) throw Error(`Refusing to overwrite ${out}: not a previous Devnet preview`);
rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });
for (const f of readdirSync(site)) if (!['tests', 'server.mjs', 'README.md', 'sitemap.xml'].includes(f)) cpSync(join(site, f), join(out, f), { recursive: true });

const program = flag('--program') ?? null, sha256 = flag('--sha256'), length = flag('--length');
if (program && !/^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(program)) throw Error('--program is not a base58 address');
writeFileSync(join(out, 'site-config.js'), `// DEVNET TEST PREVIEW: generated by scripts/devnet_preview.mjs, not the production configuration.
window.CHARTA_CONFIG = {
  cluster: 'devnet',
  rpcUrl: 'https://api.devnet.solana.com',
  programId: ${program ? `'${program}'` : 'null'},
  expectedProgram: ${sha256 && length ? `{ sha256: '${sha256}', length: ${Number(length)} }` : 'null'},
  refreshSeconds: 10,
  devnetTest: true
};
`);
writeFileSync(join(out, 'devnet-banner.js'), `// Devnet test preview banner (scripts/devnet_preview.mjs).
(() => { const b = document.createElement('div'); b.className = 'devnet-banner'; b.setAttribute('role', 'note');
  b.textContent = 'DEVNET TEST SITE · test tokens only (TEST-USDC has no value) · not the Charta launch'; document.body.prepend(b); })();
`);
writeFileSync(join(out, 'style.css'), readFileSync(join(out, 'style.css'), 'utf8') +
  '\n/* Devnet test preview */\n.devnet-banner{position:sticky;top:0;z-index:50;background:#ff9a3c;color:#2b1400;font:650 12px/1.4 var(--mono,monospace);letter-spacing:.04em;text-align:center;padding:7px 12px}\n');
// The Devnet token's on-chain metadata points here; its name says it is a test token.
const token = JSON.parse(readFileSync(join(out, 'token.json'), 'utf8'));
writeFileSync(join(out, 'token.json'), JSON.stringify({ ...token, name: 'Charta DEVNET TEST', symbol: 'tCHTA',
  description: 'Devnet test token of the Charta program. It has no value and is not the Charta launch. ' + token.description }, null, 1) + '\n');
writeFileSync(join(out, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
writeFileSync(join(out, '_headers'), readFileSync(join(out, '_headers'), 'utf8').replace('/*\n', '/*\n  X-Robots-Tag: noindex, nofollow\n'));

// The token rule card reads real mainnet tokens (USDC is real there), so it keeps its wording.
const keep = new Set(['check.html', 'check.js', 'check-core.js']);
let pages = 0, labels = 0;
for (const f of readdirSync(out)) {
  if (!/\.(html|js)$/.test(f) || keep.has(f) || f.startsWith('vendor')) continue;
  let s = readFileSync(join(out, f), 'utf8');
  s = s.replace(/\bUSDC\b/g, () => { labels++; return 'TEST-USDC'; });
  if (f.endsWith('.html')) { s = s.replace('</head>', '  <script src="devnet-banner.js" defer></script>\n</head>').replace(/<title>/, '<title>[DEVNET TEST] '); pages++; }
  writeFileSync(join(out, f), s);
}
console.log(JSON.stringify({ out, program, expectedProgram: sha256 ? { sha256, length: Number(length) } : null, pages, testUsdcLabels: labels }));
